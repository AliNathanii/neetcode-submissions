class Solution:
    def permute(self, nums: List[int]) -> List[List[int]]:
        if len(nums) == 0:  # base case if the nums list is empty
            return [[]]  # return a list containing an empty list
        
        perms = self.permute(nums[1:])  # the idea is keep calling recursively the permute function but without the first element! ie without the item at index 0
        res = []
        for p in perms:  # this loop iterates over each permutation p that was generated by the recursive call
            for i in range(len(p) + 1):  # and this loop iterates over each indices of the current permutation p
                p_copy = p.copy()  # make a copy of that permutation p
                p_copy.insert(i, nums[0])  # insert at index i the value at nums[0] ie the first value in nums list
                res.append(p_copy)  # the modified p_copy is then appended to the res list that we return
        return res